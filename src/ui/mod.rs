/// Build the Slint window, bind it to the database-backed state and wire all
/// callbacks. Returns the handle; the caller keeps it alive until
/// `ui.run()` returns (Android event loop) or drops it explicitly (tests).
pub fn create_app_window(db: Database) -> Result<AppWindow, slint::PlatformError> {
    let ui = AppWindow::new()?;
    let state = Rc::new(RefCell::new(AppState::new(db)));

    refresh_all(&state, &ui);

    // -- body selection ------------------------------------------------------
    let s = state.clone();
    let uiw = ui.as_weak();
    ui.on_select_body(move |id| {
        let Some(ui) = uiw.upgrade() else { return };
        {
            s.borrow_mut().selected_body_id = Some(id as i64);
        }
        refresh_compatibility(&s, &ui);
        ui.set_selected_body_id(id);
    });

    // -- lens selection --------------------------------------------------------
    let s = state.clone();
    let uiw = ui.as_weak();
    ui.on_select_lens(move |id| {
        let Some(ui) = uiw.upgrade() else { return };
        {
            s.borrow_mut().selected_lens_id = Some(id as i64);
        }
        refresh_compatibility(&s, &ui);
        ui.set_selected_lens_id(id);
    });

    // -- flash selection: echo the tapped unit's safety verdict ---------------
    let s = state.clone();
    let uiw = ui.as_weak();
    ui.on_select_flash(move |id| {
        let Some(ui) = uiw.upgrade() else { return };
        let flash = s.borrow().flashes.iter().find(|f| f.id == id as i64).cloned();
        if let Some(f) = flash {
            let safety = evaluate_flash(&f);
            ui.set_flash_status(SharedString::from(safety.status.as_str()));
            ui.set_flash_message(SharedString::from(safety.message));
            ui.set_flash_safe(safety.status == crate::compatibility::FlashSafetyStatus::Safe);
        }
    });

    // -- add custom gear (validated JSON -> INSERT INTO custom_gear) ----------
    let s = state.clone();
    let uiw = ui.as_weak();
    ui.on_add_custom_gear(move |name, specs_json| {
        let Some(ui) = uiw.upgrade() else { return };
        let name = name.to_string();
        let specs_raw = specs_json.to_string();
        // Reject empty names and malformed JSON before touching SQLite.
        if name.trim().is_empty() {
            ui.set_status_line(SharedString::from("ERROR: gear name must not be empty."));
            return;
        }
        let parsed: Result<serde_json::Value, _> = serde_json::from_str(&specs_raw);
        let value = match parsed {
            Ok(v) => v,
            Err(e) => {
                ui.set_status_line(SharedString::from(format!(
                    "ERROR: invalid specs_json: {e}"
                )));
                return;
            }
        };
        let mut st = s.borrow_mut();
        let item = CustomGear::new(name.trim(), st.current_gear_type(), &value);
        match st.db.insert_custom_gear(&item) {
            Ok(_id) => {
                st.custom_gear = st.db.all_custom_gear().unwrap_or_default();
                ui.set_custom_gear(gear_rows(&st.custom_gear));
                let counts = st.db.table_counts().unwrap_or((0, 0, 0, 0));
                ui.set_status_line(SharedString::from(format!(
                    "Saved '{}' ({}) - {} custom items total.",
                    item.user_name,
                    item.gear_type.label(),
                    counts.3
                )));
            }
            Err(e) => ui.set_status_line(SharedString::from(format!("ERROR: {e}"))),
        }
    });

    // -- delete custom gear ----------------------------------------------------
    let s = state.clone();
    let uiw = ui.as_weak();
    ui.on_delete_custom_gear(move |id| {
        let Some(ui) = uiw.upgrade() else { return };
        let mut st = s.borrow_mut();
        match st.db.delete_custom_gear(id as i64) {
            Ok(true) => {
                st.custom_gear.retain(|g| g.id != id as i64);
                ui.set_custom_gear(gear_rows(&st.custom_gear));
                ui.set_status_line(SharedString::from("Deleted custom gear row."));
            }
            Ok(false) => ui.set_status_line(SharedString::from("ERROR: row not found.")),
            Err(e) => ui.set_status_line(SharedString::from(format!("ERROR: {e}"))),
        }
    });

    // -- cycle SD_CARD -> BATTERY -> FILTER -------------------------------------
    let s = state.clone();
    let uiw = ui.as_weak();
    ui.on_cycle_gear_type(move || {
        let Some(ui) = uiw.upgrade() else { return };
        let mut st = s.borrow_mut();
        st.gear_type_idx = (st.gear_type_idx + 1) % GearType::ALL.len();
        ui.set_gear_type_label(SharedString::from(st.current_gear_type().label()));
    });

    // -- manual reload (header button) ------------------------------------------
    let s = state.clone();
    let uiw = ui.as_weak();
    ui.on_reload(move || {
        let Some(ui) = uiw.upgrade() else { return };
        s.borrow_mut().reload_from_db();
        refresh_all(&s, &ui);
    });

    Ok(ui)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn test_db() -> Database {
        Database::open_in_memory().unwrap()
    }

    #[test]
    fn specs_summary_flattens_json() {
        let s = specs_summary("{\"read_speed\": 300, \"capacity_gb\": 128}");
        assert!(s.contains("read_speed: 300"), "{s}");
        assert!(s.contains("capacity_gb: 128"), "{s}");
        // invalid JSON falls back to raw text
        assert_eq!(specs_summary("{not json"), "{not json");
    }

    #[test]
    fn model_builders_match_seed_data() {
        let db = test_db();
        let bodies = db.all_bodies().unwrap();
        let lenses = db.all_lenses().unwrap();
        let flashes = db.all_flashes().unwrap();

        let bm = body_rows(&bodies);
        assert_eq!(bm.row_count(), bodies.len());

        let lm = lens_rows(&lenses);
        assert_eq!(lm.row_count(), lenses.len());

        let fm = flash_rows(&flashes);
        assert_eq!(fm.row_count(), flashes.len());
        // The legacy Metronix seed row must surface HIGH_VOLTAGE_RISK.
        let risky = fm
            .iter()
            .find(|r| r.model_name == "Metronix 56 (legacy)")
            .expect("seed flash present");
        assert!(!risky.safe);
        assert_eq!(&risky.safety_status.to_string(), "HIGH_VOLTAGE_RISK");
    }

    #[test]
    fn state_defaults_pick_interesting_pairing() {
        let state = AppState::new(test_db());
        // Newest release (Alpha 7C II, 2023) is first in the ordered query...
        assert_eq!(state.body().unwrap().marketing_name, "Alpha 7C II");
        // ...with an FE lens so a native pairing renders immediately.
        assert_eq!(state.lens().unwrap().target_sensor, SensorType::FullFrame);
    }
}
