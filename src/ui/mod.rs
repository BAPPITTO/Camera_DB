//! Slint application layer.
//!
//! The `.slint` markup in `ui/app-window.slint` is compiled ahead-of-time by
//! `build.rs` (slint-build) into `$OUT_DIR/slint_generated.rs`, which is
//! included below. This module owns the *imperative* half of the binding:
//! loading rows from SQLite, flattening them into Slint models and wiring the
//! declarative callbacks back into `crate::compatibility` business logic.

use std::cell::RefCell;
use std::rc::Rc;

use slint::{ComponentHandle, ModelRc, SharedString, VecModel};

use crate::compatibility::{calculate_compatibility, evaluate_flash, CompatibilityStatus};
use crate::db::Database;
use crate::models::{trim_num, CameraBody, CustomGear, Flash, GearType, Lens, SensorType};

// Generated by `slint_build::compile_with_config("ui/app-window.slint", ...)`
// in build.rs. Defines `AppWindow`, `BodyRow`, `LensRow`, `FlashRow`,
// `GearRow`, `NoteRow`, `StatusBadge` in this scope.
include!(concat!(env!("OUT_DIR"), "/slint_generated.rs"));

/// Mutable app state shared between the Slint callbacks (Slint runs everything
/// on one UI thread; Rc/RefCell is the correct non-atomic sharing model).
struct AppState {
    db: Database,
    bodies: Vec<CameraBody>,
    lenses: Vec<Lens>,
    flashes: Vec<Flash>,
    custom_gear: Vec<CustomGear>,
    selected_body_id: Option<i64>,
    selected_lens_id: Option<i64>,
    /// Index into `GearType::ALL` cycled by the "Type:" button.
    gear_type_idx: usize,
}

impl AppState {
    fn new(db: Database) -> Self {
        let bodies = db.all_bodies().unwrap_or_default();
        let lenses = db.all_lenses().unwrap_or_default();
        let flashes = db.all_flashes().unwrap_or_default();
        let custom_gear = db.all_custom_gear().unwrap_or_default();

        let selected_body_id = bodies.first().map(|b| b.id);
        // Default to an FE lens so the interesting crop-mode maths is visible
        // immediately after first launch.
        let selected_lens_id = lenses
            .iter()
            .find(|l| l.target_sensor == SensorType::FullFrame)
            .or(lenses.first())
            .map(|l| l.id);

        Self {
            db,
            bodies,
            lenses,
            flashes,
            custom_gear,
            selected_body_id,
            selected_lens_id,
            gear_type_idx: 0,
        }
    }

    fn reload_from_db(&mut self) {
        self.bodies = self.db.all_bodies().unwrap_or_default();
        self.lenses = self.db.all_lenses().unwrap_or_default();
        self.flashes = self.db.all_flashes().unwrap_or_default();
        self.custom_gear = self.db.all_custom_gear().unwrap_or_default();
        if self.selected_body_id.map_or(true, |id| !self.bodies.iter().any(|b| b.id == id)) {
            self.selected_body_id = self.bodies.first().map(|b| b.id);
        }
        if self.selected_lens_id.map_or(true, |id| !self.lenses.iter().any(|l| l.id == id)) {
            self.selected_lens_id = self
                .lenses
                .iter()
                .find(|l| l.target_sensor == SensorType::FullFrame)
                .or(self.lenses.first())
                .map(|l| l.id);
        }
    }

    fn body(&self) -> Option<&CameraBody> {
        self.bodies.iter().find(|b| Some(b.id) == self.selected_body_id)
    }

    fn lens(&self) -> Option<&Lens> {
        self.lenses.iter().find(|l| Some(l.id) == self.selected_lens_id)
    }

    fn current_gear_type(&self) -> GearType {
        GearType::ALL[self.gear_type_idx % GearType::ALL.len()]
    }
}

// ---------------------------------------------------------------------------
// Model builders (Rust structs -> flattened Slint row structs)
// ---------------------------------------------------------------------------

fn body_rows(bodies: &[CameraBody]) -> ModelRc<BodyRow> {
    Rc::new(VecModel::from(
        bodies
            .iter()
            .map(|b| BodyRow {
                id: b.id as i32,
                marketing_name: SharedString::from(&b.marketing_name),
                model_name: SharedString::from(&b.model_name),
                sensor_label: SharedString::from(b.sensor_type.to_string()),
                megapixels_label: SharedString::from(format!(
                    "{} MP",
                    trim_num(b.base_megapixels)
                )),
                ibis_label: SharedString::from(if b.has_ibis { "IBIS" } else { "-" }),
                year_label: SharedString::from(match b.release_year {
                    Some(y) => y.to_string(),
                    None => "-".to_string(),
                }),
            })
            .collect::<Vec<_>>(),
    )) as ModelRc<BodyRow>
}

fn lens_rows(lenses: &[Lens]) -> ModelRc<LensRow> {
    Rc::new(VecModel::from(
        lenses
            .iter()
            .map(|l| LensRow {
                id: l.id as i32,
                marketing_name: SharedString::from(&l.marketing_name),
                model_name: SharedString::from(&l.model_name),
                mount: SharedString::from(l.mount_designation.as_str()),
                target_label: SharedString::from(l.target_sensor.to_string()),
                focal_label: SharedString::from(l.focal_label()),
                aperture_label: SharedString::from(format!("f/{}", trim_num(l.max_aperture_min))),
                oss_label: SharedString::from(if l.has_oss { "OSS" } else { "-" }),
                weight_label: SharedString::from(match l.weight_grams {
                    Some(w) => format!("{w} g"),
                    None => "-".to_string(),
                }),
            })
            .collect::<Vec<_>>(),
    )) as ModelRc<LensRow>
}

fn flash_rows(flashes: &[Flash]) -> ModelRc<FlashRow> {
    Rc::new(VecModel::from(
        flashes
            .iter()
            .map(|f| {
                // Safety verdict computed once per reload by the pure
                // compatibility layer - no logic lives in the markup.
                let safety = evaluate_flash(f);
                FlashRow {
                    id: f.id as i32,
                    model_name: SharedString::from(&f.model_name),
                    gn_label: SharedString::from(format!("GN {}", trim_num(f.guide_number))),
                    voltage_label: SharedString::from(format!("{:.1} V", f.trigger_voltage)),
                    ttl_label: SharedString::from(if f.ttl_compatible { "TTL" } else { "Manual" }),
                    safety_status: SharedString::from(safety.status.as_str()),
                    safe: safety.status == crate::compatibility::FlashSafetyStatus::Safe,
                    message: SharedString::from(safety.message),
                }
            })
            .collect::<Vec<_>>(),
    )) as ModelRc<FlashRow>
}

/// Compact one-line summary of a specs JSON blob, e.g.
/// `{"read_speed":300,"capacity_gb":128}` -> `read_speed: 300 · capacity_gb: 128`.
/// Falls back to the raw string when it does not parse.
fn specs_summary(raw: &str) -> String {
    let v: serde_json::Value = serde_json::from_str(raw).unwrap_or(serde_json::Value::Null);
    if let Some(o) = v.as_object() {
        let parts: Vec<String> = o
            .iter()
            .map(|(k, val)| format!("{k}: {}", compact_json_value(val)))
            .collect();
        if !parts.is_empty() {
            return parts.join(" \u{b7} ");
        }
    }
    raw.trim().to_string()
}

fn compact_json_value(v: &serde_json::Value) -> String {
    match v {
        serde_json::Value::Number(n) => n.to_string(),
        serde_json::Value::String(s) => s.clone(),
        serde_json::Value::Bool(b) => b.to_string(),
        serde_json::Value::Null => "-".to_string(),
        other => other.toString(),
    }
}

fn gear_rows(gear: &[CustomGear]) -> ModelRc<GearRow> {
    Rc::new(VecModel::from(
        gear.iter()
            .map(|g| GearRow {
                id: g.id as i32,
                user_name: SharedString::from(&g.user_name),
                type_label: SharedString::from(g.gear_type.label()),
                specs_summary: SharedString::from(specs_summary(&g.specs_json)),
                specs_json: SharedString::from(&g.specs_json),
            })
            .collect::<Vec<_>>(),
    )) as ModelRc<GearRow>
}

// ---------------------------------------------------------------------------
// Binding: push Rust state into the Slint window + recompute results
// ---------------------------------------------------------------------------

fn refresh_all(state: &Rc<RefCell<AppState>>, ui: &AppWindow) {
    {
        let s = state.borrow();
        ui.set_bodies(body_rows(&s.bodies));
        ui.set_lenses(lens_rows(&s.lenses));
        ui.set_flashes(flash_rows(&s.flashes));
        ui.set_custom_gear(gear_rows(&s.custom_gear));
        ui.set_selected_body_id(s.selected_body_id.unwrap_or(-1) as i32);
        ui.set_selected_lens_id(s.selected_lens_id.unwrap_or(-1) as i32);
        ui.set_gear_type_label(SharedString::from(s.current_gear_type().label()));
        let counts = s.db.table_counts().unwrap_or((0, 0, 0, 0));
        ui.set_status_line(SharedString::from(format!(
            "{} bodies / {} lenses / {} flashes / {} custom items in local SQLite",
            counts.0, counts.1, counts.2, counts.3
        )));
    }
    refresh_compatibility(state, ui);
}

/// Run `calculate_compatibility` for the current selection and push every
/// derived value into the declarative result card.
fn refresh_compatibility(state: &Rc<RefCell<AppState>>, ui: &AppWindow) {
    let s = state.borrow();
    let (Some(body), Some(lens)) = (s.body(), s.lens()) else {
        ui.set_status_code(SharedString::from("UNKNOWN"));
        ui.set_status_label(SharedString::from("Select a body and a lens"));
        ui.set_compat_notes(ModelRc::from(Rc::new(VecModel::<NoteRow>::default())));
        return;
    };

    let r = calculate_compatibility(body, lens);

    ui.set_body_label(SharedString::from(format!(
        "{} [{} \u{b7} {} MP]",
        body.marketing_name,
        body.sensor_type,
        trim_num(body.base_megapixels)
    )));
    ui.set_lens_label(SharedString::from(format!(
        "{} [{} \u{b7} {}]",
        lens.marketing_name,
        lens.mount_designation,
        lens.focal_label()
    )));
    ui.set_status_code(SharedString::from(r.status.as_str()));
    ui.set_status_label(SharedString::from(r.status.label()));
    ui.set_focal_label(SharedString::from(r.focal_range_label()));
    ui.set_mp_label(SharedString::from(format!(
        "{:.1} MP{}",
        r.effective_megapixels,
        if r.status == CompatibilityStatus::CropMode {
            " (crop)"
        } else {
            ""
        }
    )));
    ui.set_penalty_label(SharedString::from(if r.resolution_penalty {
        format!(
            "Resolution penalty: {:.1}% of native retained.",
            if body.base_megapixels > 0.0 {
                r.effective_megapixels / body.base_megapixels * 100.0
            } else {
                0.0
            }
        )
    } else {
        String::new()
    }));
    ui.set_compat_notes(Rc::new(VecModel::from(
        r.notes
            .iter()
            .map(|n| NoteRow {
                text: SharedString::from(n),
            })
            .collect::<Vec<_>>(),
    )) as ModelRc<NoteRow>);
}

